"""Generate docs/TOOL_REFERENCE.md from the live tool surface + metadata.

This generator enumerates the actually-registered tools,
joins each with its metadata and one-line docstring, and emits a searchable
reference grouped by category with maturity/interaction badges: the same
data ``tool_catalog`` serves at runtime, in a browsable form.

Run: ``python scripts/gen_tool_reference.py`` (writes docs/TOOL_REFERENCE.md).
Pure Python; no Altium. ``build_reference()`` returns the markdown string so
tests can assert on it without touching disk.
"""

from __future__ import annotations

import asyncio
from pathlib import Path

_INTERACTION_NOTE = {
    "readonly": "read-only",
    "silent": "mutates, no dialog",
    "modal": "opens a blocking Altium dialog (answered by the dialog driver "
             "or a human)",
    "partial": "leaves the job incomplete (needs a follow-up tool)",
}

_MATURITY_NOTE = {
    "offline": "pure Python, CI-tested, no Altium",
    # Means every command the tool sends has a simulator handler, so the
    # call CAN be driven with no Altium; not that a test drives it today.
    "simulator": "every command it sends runs against the Altium simulator",
    "live_verified": "recorded against a live Altium by Altium Agent's own "
                     "release run (tools/live_verified.json)",
    "live_unverified": "needs a running Altium and has no Altium Agent live "
                       "record yet (being listed is not evidence it was run)",
}

#: Group order follows docs/TOOL_NAMING.md. Unlisted categories are
#: appended, so a new one is never dropped, only badly placed.
_CATEGORY_ORDER = [
    "meta", "application", "project", "schematic", "pcb", "library",
    "generic", "routing", "placement", "reference", "analysis", "design",
    "audit", "other",
]


def _collect() -> list[dict]:
    from mcp.server.fastmcp import FastMCP
    from altium_agent.tools import register_backend
    from altium_agent.tools import metadata as M

    mcp = FastMCP("gen")
    register_backend(mcp, "altium")
    tools = asyncio.run(mcp.list_tools())
    out = []
    for t in tools:
        md = M.tool_metadata(t.name)
        summary = (t.description or "").strip().split("\n", 1)[0]
        md["summary"] = summary
        out.append(md)
    return out


def build_reference() -> str:
    records = _collect()
    by_cat: dict[str, list[dict]] = {}
    for r in records:
        by_cat.setdefault(r["category"], []).append(r)

    from collections import Counter
    maturity = Counter(r["maturity"] for r in records)
    interaction = Counter(r["interaction"] for r in records)

    lines = [
        "# Tool reference",
        "",
        "_Auto-generated by `scripts/gen_tool_reference.py` from the live "
        "tool surface + `tools/metadata.py`. Do not edit by hand; "
        "`tests/test_gen_tool_reference.py` fails when it is stale._",
        "",
        f"**{len(records)} tools** across {len(by_cat)} groups.",
        "",
        "**Maturity**: "
        + "; ".join(f"`{k}` = {v}" for k, v in _MATURITY_NOTE.items())
        + ".",
        "",
        "**Interaction**: "
        + "; ".join(f"`{k}` = {v}" for k, v in _INTERACTION_NOTE.items())
        + ".",
        "",
        "| Maturity | Tools |",
        "|---|---|",
    ]
    for k in _MATURITY_NOTE:
        lines.append(f"| {k} | {maturity.get(k, 0)} |")
    lines += ["", "| Interaction | Tools |", "|---|---|"]
    for k in _INTERACTION_NOTE:
        lines.append(f"| {k} | {interaction.get(k, 0)} |")
    lines.append("")

    ordered_cats = [c for c in _CATEGORY_ORDER if c in by_cat]
    ordered_cats += [c for c in sorted(by_cat) if c not in _CATEGORY_ORDER]

    for cat in ordered_cats:
        rows = sorted(by_cat[cat], key=lambda r: r["name"])
        lines.append(f"## {cat} ({len(rows)})")
        lines.append("")
        lines.append("| Tool | Interaction | Maturity | Summary |")
        lines.append("|---|---|---|---|")
        for r in rows:
            summ = r["summary"].replace("|", "\\|")
            lines.append(
                f"| `{r['name']}` | {r['interaction']} | {r['maturity']} | {summ} |"
            )
        lines.append("")

    return "\n".join(lines)


def main() -> int:
    repo_root = Path(__file__).resolve().parents[1]
    out_path = repo_root / "docs" / "TOOL_REFERENCE.md"
    out_path.write_text(build_reference(), encoding="utf-8")
    print(f"Wrote {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
